#!/usr/bin/env node
// No model: install a fake-agent session, or run its one bounded command.
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { performance } = require('node:perf_hooks');
const { setTimeout: sleep } = require('node:timers/promises');

const MAX_MINUTES = 120;
const ENDPOINT = 'https://api.github.com/zen';
// Kept verbatim from dispatch-comment.sh at the deployment's 427ce229 pin.
const CANARY = { execute: { title: 'Redaction control',
  command: "printf 'redaction trial: gh%s_%s\\n' p FAKEREDACTIONCANARY0123456789abcdef" } };

function minutes(value) {
  // Threat: unbounded runtime/cost or shell text smuggled through dispatch.
  if (typeof value !== 'string' || !/^[1-9][0-9]*$/.test(value) ||
      value.length > 3 || Number(value) > MAX_MINUTES) {
    throw Error(`minutes must be a canonical integer from 1 to ${MAX_MINUTES}`);
  }
  return Number(value);
}

function validate(value, egress) {
  const duration = minutes(value);
  if (!['on', 'off'].includes(egress)) throw Error('egress must be on or off');
  return { minutes: duration, config: `.github/agentic-job/soak-${egress}.toml` };
}

function config(hosted, egress) {
  validate('90', egress);
  // Generate committed variants, never a different host baseline. Fail on drift.
  const marker = '[egress]\nproxy = false';
  if (hosted.split(marker).length !== 2 || !hosted.includes('[setup]\n')) {
    throw Error('hosted.toml changed: review soak derivation');
  }
  return '# Generated by node workflow/soak.cjs configs; do not edit.\n' + hosted
    .replace(/# The egress lockdown is off,[\s\S]*?(?=\[egress\])/, '# Soak-only A/B override; ordinary dispatch keeps hosted.toml unchanged.\n')
    .replace(marker, `[egress]\nproxy = ${egress === 'on'}\nrust-proxy = true\nwrite-policy = ${egress === 'on'}`)
    .replace('[setup]\n', '[setup]\nscript = "workflow/soak.cjs"\n');
}

function setup(home, value) {
  const duration = minutes(value); // Missing upstream transport must fail, not default.
  const directory = path.join(home, '.config/fake-agent');
  fs.mkdirSync(directory, { recursive: true });
  fs.copyFileSync(__filename, path.join(directory, 'soak.cjs'));
  const steps = [CANARY, { execute: { title: 'Bounded HTTP soak',
    command: `node "{home}/.config/fake-agent/soak.cjs" loop ${duration}` } }];
  fs.writeFileSync(path.join(directory, 'demo.json'), JSON.stringify(steps, null, 2) + '\n');
}

function request(deadlineSeconds) {
  // curl, unlike Node's HTTP client, uses the harness HTTPS_PROXY and CA settings.
  // No redirects, retries, credentials, response body or dispatcher-selected URL.
  const result = spawnSync('curl', ['--silent', '--show-error', '--output', '/dev/null',
    '--write-out', '%{http_code}', '--connect-timeout', String(Math.min(10, deadlineSeconds)),
    '--max-time', String(deadlineSeconds), ENDPOINT],
  { encoding: 'utf8', timeout: Math.ceil(deadlineSeconds * 1000) + 1000, maxBuffer: 8192 });
  return { status: /^[0-9]{3}$/.test(result.stdout || '') ? result.stdout : '000',
    transport: result.error?.code || result.signal || result.status || 0 };
}

async function loop(value, home, { now = () => performance.now(), wait = sleep,
  get = request, emit = line => fs.writeSync(1, line + '\n'), minuteMs = 60000 } = {}) {
  const duration = minutes(value);
  const start = now();
  const end = start + duration * minuteMs;
  let failures = 0;
  let samples = 0;
  for (let tick = start; tick < end; tick += minuteMs) {
    await wait(Math.max(0, tick - now()));
    if (now() >= end) break;
    const result = get(Math.max(0.001, Math.min(20, (end - now()) / 1000)));
    if (result.transport !== 0 || !/^2[0-9]{2}$/.test(result.status)) failures++;
    samples++;
    // Synchronous write: no stdio buffering inside this process.
    emit(`${new Date().toISOString()} elapsed_s=${((now() - start) / 1000).toFixed(3)} http_status=${result.status} transport_failure=${result.transport}`);
  }
  await wait(Math.max(0, end - now()));
  const summary = `Soak completed ${duration} minute(s): ${samples} samples, ${failures} HTTP/transport failures. No inference or application changes.`;
  const out = path.join(home, 'out');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'outcome.json'), JSON.stringify({ summary, tests: [], stopped_early: null }) + '\n');
  fs.writeFileSync(path.join(out, 'safe-outputs.jsonl'), JSON.stringify({ type: 'noop', message: summary }) + '\n');
}

async function main() {
  const [mode, value] = process.argv.slice(2);
  if (!mode) return setup(process.env.HOME, process.env.SOAK_MINUTES);
  if (mode === 'loop') return loop(value, process.env.HOME);
  if (mode === 'validate') {
    const result = validate(process.env.MINUTES, process.env.EGRESS);
    fs.appendFileSync(process.env.GITHUB_OUTPUT, `minutes=${result.minutes}\nconfig=${result.config}\n`);
    return;
  }
  if (mode === 'configs') {
    const hosted = fs.readFileSync('.github/agentic-job/hosted.toml', 'utf8');
    for (const egress of ['on', 'off']) fs.writeFileSync(validate('90', egress).config, config(hosted, egress));
    return;
  }
  throw Error('expected no arguments (setup), loop MINUTES, validate, or configs');
}

module.exports = { MAX_MINUTES, ENDPOINT, CANARY, minutes, validate, config, setup, request, loop };
if (require.main === module) main().catch(error => { console.error(error.message); process.exitCode = 1; });
